
/*
 * StoryForge Manuscript View
 *
 * Builds a continuous, read-only manuscript using
 * the chapters and scenes already stored in a project.
 *
 * This module does not modify or save project data.
 */

import { countProjectWords } from "./wordCount.js";


// ============================================================
// HTML ESCAPING
// ============================================================

/*
 * Escape text before inserting it into HTML.
 *
 * Project and chapter titles are user-provided, so they
 * must be escaped to avoid being interpreted as HTML.
 */
function escapeHTML(value) {
    return String(value ?? "").replace(
        /[&<>"']/g,
        character => ({
            "&": "&amp;",
            "<": "&lt;",
            ">": "&gt;",
            '"': "&quot;",
            "'": "&#39;"
        })[character]
    );
}


// ============================================================
// WORD COUNT FORMATTING
// ============================================================

/*
 * Display word counts with thousands separators
 * and the correct singular/plural label.
 */
function formatWordCount(count) {
    const label = count === 1 ? "word" : "words";

    return `${count.toLocaleString()} ${label}`;
}


// ============================================================
// SCENE RENDERING
// ============================================================

/*
 * Render one scene's writing content.
 *
 * Scene titles are deliberately excluded because
 * they are organisational labels and may not be
 * intended to appear in the finished manuscript.
 *
 * Scene content contains HTML generated by TipTap.
 */
function renderManuscriptScene(scene, index) {
    const sceneBreak = index > 0
        ? '<div class="scene-break" aria-label="Scene break">* * *</div>'
        : "";

    const content = scene.content || "";

    return `
        ${sceneBreak}

        <div
            class="manuscript-scene"
            data-scene-id="${escapeHTML(scene.id)}"
        >
            ${content}
        </div>
    `;
}


// ============================================================
// CHAPTER RENDERING
// ============================================================

/*
 * Render a chapter heading followed by all of
 * its scenes in their existing order.
 */
function renderManuscriptChapter(chapter) {
    const scenes = chapter.scenes || [];

    return `
        <section
            class="manuscript-chapter"
            data-chapter-id="${escapeHTML(chapter.id)}"
        >

            <h2>${escapeHTML(chapter.title)}</h2>

            ${
                scenes.length === 0

                    ? `
                        <p class="text-muted text-center">
                            This chapter has no scenes yet.
                        </p>
                    `

                    : scenes.map(
                        (scene, index) =>
                            renderManuscriptScene(scene, index)
                    ).join("")
            }

        </section>
    `;
}


// ============================================================
// FULL MANUSCRIPT VIEW
// ============================================================

/*
 * Render the complete manuscript.
 *
 * This function is called by app.js:
 *
 * renderManuscript(app, project);
 *
 * The Back button is also handled by app.js.
 */
export function renderManuscript(container, project) {
    const chapters = project.chapters || [];

    const projectWordCount = countProjectWords(project);

    container.innerHTML = `
        <div class="container mt-4 mb-5">

            <!-- Return to the selected project. -->
            <button
                id="back-to-project"
                class="btn btn-outline-secondary mb-4"
                type="button"
            >
                ← Back to Project
            </button>


            <!-- MANUSCRIPT INFORMATION -->

            <div class="mb-4">

                <h1>${escapeHTML(project.title)}</h1>

                <p class="text-muted">
                    ${chapters.length} chapters
                    •
                    ${formatWordCount(projectWordCount)}
                </p>

                <p class="text-muted small">
                    Read-only manuscript preview
                </p>

            </div>


            <!-- CONTINUOUS MANUSCRIPT -->

            <article class="manuscript-page">

                ${
                    chapters.length === 0

                        ? `
                            <p class="text-muted">
                                No chapters to display yet.
                            </p>
                        `

                        : chapters.map(
                            chapter =>
                                renderManuscriptChapter(chapter)
                        ).join("")
                }

            </article>

        </div>
    `;
}
